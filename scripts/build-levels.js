// Offline level authoring: shuffled full boxes, solved before shipping.
const fs = require('node:fs');
const path = require('node:path');
const e = require('../utils/engine');
const {TOTAL_LEVELS,profile} = require('../utils/level-plan');
const {solveExact} = require('./exact-solver');
let seed = 361092;
const rand = () => {seed = (Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296;};
const canonical = board => board.map(t=>t.join('')).sort().join('|');
const bound = board => board.reduce((sum,t)=>sum+t.filter((c,i)=>!i||c!==t[i-1]).length,0) - new Set(board.flat()).size;
function solve(board, budget=35000) {
  let nodes=0;
  // Find a verified reference solution; do not claim an optimal move count.
  for(let depth=bound(board)+8;depth<=60;depth+=6) {
    const seen=new Map();
    const search=(current,left,trail)=>{
      if(++nodes>budget) return null;
      if(e.won(current)) return trail;
      if(left<bound(current)||left===0)return null;
      const key=canonical(current);
      if((seen.get(key)??-1)>=left)return null;
      seen.set(key,left);
      const targets=new Set();
      const moves=e.legalMoves(current).filter(m=>{
        const src=current[m.from],dst=current[m.to];
        if(!dst.length&&src.every(c=>c===src[0]))return false;
        const signature=`${src.join('')}>${dst.join('')}`;
        if(targets.has(signature))return false;
        targets.add(signature);return true;
      }).sort((a,b)=>bound(a.next)-bound(b.next));
      for(const m of moves) {const result=search(m.next,left-1,trail.concat([[m.from,m.to]]));if(result)return result;if(nodes>budget)return null;}
      return null;
    };
    const result=search(board,depth,[]);
    if(result)return result;
    if(nodes>budget)return null;
  }
  return null;
}
const levels=[];
const used = new Set();
for(let level=1;level<=TOTAL_LEVELS;level++) {
  const plan = profile(level);
  const {colors,spare} = plan;
  let accepted;
  for(let attempt=0;attempt<3000;attempt++) {
    const bag=Array.from({length:colors*4},(_,i)=>Math.floor(i/4));
    for(let i=bag.length-1;i>0;i--){const j=Math.floor(rand()*(i+1));[bag[i],bag[j]]=[bag[j],bag[i]];}
    const board=Array.from({length:colors},(_,i)=>bag.slice(i*4,i*4+4)).concat(Array.from({length:spare},()=>[]));
    if(board.some(e.complete)||bound(board)<colors*2||used.has(canonical(board)))continue;
    const solution=solve(board);
    const minimum=plan.boss?colors*3+2:plan.stage===3&&!plan.rest?colors*3-2:0;
    if(solution && solution.length>=minimum) {accepted={...plan,board,solution};used.add(canonical(board));break;}
  }
  if(!accepted)throw Error(`No suitable level ${level}`);
  accepted.solution=solveExact(accepted.board,accepted.solution.length);
  accepted.minSteps=accepted.solution.length;
  levels.push(accepted);
  console.log(`Level ${level}: ${colors} colors, ${spare} spare, minimum ${accepted.minSteps} moves (${plan.label})`);
}
fs.writeFileSync(path.join(__dirname,'../utils/levels.js'),'// Generated by scripts/build-levels.js; 100 offline-proven optimal solutions.\nmodule.exports = '+JSON.stringify(levels,null,2)+';\n');
