const assert=require('node:assert/strict');
const {starsFor,starText}=require('../utils/rating');
const {pointFrom,bindInput}=require('../utils/input');
assert.equal(starsFor(12,12),3);
assert.equal(starsFor(13,12),2);
assert.equal(starsFor(17,12),2);
assert.equal(starsFor(18,12),1);
assert.equal(starsFor(1000,12),1);
assert.equal(starsFor(11,12),0);
assert.equal(starText(3),'★★★');assert.equal(starText(1),'★☆☆');
for(const e of [{changedTouches:[{clientX:0,clientY:20}]},{touches:[{pageX:0,pageY:20}]},{x:0,y:20}])assert.deepEqual(pointFrom(e),{x:0,y:20});
assert.equal(pointFrom({changedTouches:[]}),null);
const handlers={},calls=[];
const api={};for(const name of ['TouchStart','TouchEnd','TouchCancel','MouseUp'])api['on'+name]=fn=>{handlers[name]=fn;};
bindInput(api,(x,y)=>calls.push([x,y]));
handlers.TouchStart({touches:[{x:100,y:200}]});
handlers.TouchEnd({changedTouches:[]});
handlers.MouseUp({x:100,y:200,button:0});
assert.deepEqual(calls,[[100,200]],'Touch start/end plus synthetic mouse must fire once');
handlers.TouchStart({touches:[{clientX:100,clientY:200}]});handlers.TouchEnd({});
assert.equal(calls.length,2,'Rapid deliberate touch taps must not be suppressed');
handlers.TouchEnd({changedTouches:[{pageX:250,pageY:400}]});
assert.deepEqual(calls[2],[250,400],'End-only runtimes still work');
handlers.MouseUp({x:330,y:450,button:0});assert.deepEqual(calls[3],[330,450]);
handlers.MouseUp({x:331,y:450,button:2});assert.equal(calls.length,4,'Ignore right click');
handlers.TouchStart({touches:[{clientX:100,clientY:200}]});handlers.TouchCancel();
handlers.TouchEnd({changedTouches:[{clientX:250,clientY:400}]});assert.deepEqual(calls[calls.length-1],[250,400]);
console.log('Ratings: all star boundaries pass. Input: touch, mouse, coordinate variants, end-only and synthetic-event dedup pass.');
